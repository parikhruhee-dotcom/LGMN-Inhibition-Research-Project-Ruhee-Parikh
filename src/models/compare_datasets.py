"""Did expanding the dataset actually improve the model?

More data is assumed to help, and on a 180-compound set adding 9 compounds
and 6 scaffolds produced numbers that look like an improvement: MAE from
0.772 to 0.728, and R2 crossing from -0.195 to +0.029. Quoting that as
"expanding the dataset made the model work" would be wrong, which is what
this script exists to establish.

Two things are checked, and they disagree in an instructive way:

- **Is the difference larger than fold-to-fold noise?** Scaffold-split folds
  on a set this small vary by +/-0.4 log units, so a 0.044 difference in mean
  MAE is not evidence of anything on its own.
- **Is the direction consistent across models?** A change too small to be
  significant can still be real if every independent model moves the same
  way. That is weak evidence, and is reported as weak.

Writes:
    docs/DATA_EXPANSION.md

Usage:
    python src/models/compare_datasets.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "results"
PROCESSED = ROOT / "data" / "processed"
DOCS = ROOT / "docs"

BASELINE_MODEL = "mean_baseline"


def fold_scores(metrics: pd.DataFrame, model: str, features: str) -> pd.Series:
    return metrics[
        metrics["split"].eq("scaffold")
        & metrics["model"].eq(model)
        & metrics["features"].eq(features)
    ]["mae"]


def compare(before: Path, after: Path) -> dict:
    metrics_before = pd.read_csv(before / "metrics.csv")
    metrics_after = pd.read_csv(after / "metrics.csv")
    summary_before = pd.read_csv(before / "summary.csv")
    summary_after = pd.read_csv(after / "summary.csv")

    def best(summary: pd.DataFrame) -> pd.Series:
        scaffold = summary[summary["split"].eq("scaffold")]
        learned = scaffold[scaffold["model"].ne(BASELINE_MODEL)]
        return learned.sort_values("mae_mean").iloc[0]

    best_before, best_after = best(summary_before), best(summary_after)

    # Compare like with like: the same model and feature block on both
    # datasets, since the best configuration can change between runs for
    # reasons unrelated to the data.
    pairs = []
    combos = (
        metrics_before[metrics_before["model"].ne(BASELINE_MODEL)][
            ["model", "features"]
        ]
        .drop_duplicates()
        .itertuples(index=False)
    )
    for model, features in combos:
        x = fold_scores(metrics_before, model, features)
        y = fold_scores(metrics_after, model, features)
        if x.empty or y.empty:
            continue
        pairs.append(
            {
                "model": model,
                "features": features,
                "mae_before": x.mean(),
                "sd_before": x.std(),
                "mae_after": y.mean(),
                "sd_after": y.std(),
                "delta": y.mean() - x.mean(),
                "improved": bool(y.mean() < x.mean()),
            }
        )
    table = pd.DataFrame(pairs)

    x = fold_scores(metrics_before, best_before["model"], best_before["features"])
    y = fold_scores(metrics_after, best_after["model"], best_after["features"])
    _, p_value = stats.ttest_ind(x, y, equal_var=False)

    improved = int(table["improved"].sum()) if not table.empty else 0
    total = len(table)
    # Probability of this many or more improvements if direction were a
    # coin flip. Weak evidence by construction, and labelled as such.
    sign_p = (
        float(stats.binomtest(improved, total, 0.5, alternative="greater").pvalue)
        if total
        else float("nan")
    )

    return {
        "best_before": best_before,
        "best_after": best_after,
        "table": table,
        "p_value": float(p_value),
        "improved": improved,
        "total": total,
        "sign_p": sign_p,
        "fold_sd": float(max(x.std(), y.std())),
    }


def write_doc(result: dict, n_before: int, n_after: int,
              scaffolds_before: int, scaffolds_after: int) -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    best_before = result["best_before"]
    best_after = result["best_after"]
    table = result["table"]

    significant = result["p_value"] < 0.05

    lines = [
        "# Did expanding the dataset help?",
        "",
        "Generated by `src/models/compare_datasets.py`.",
        "",
        f"The ChEMBL-derived set holds **{n_before} compounds over "
        f"{scaffolds_before} scaffolds**. Adding the",
        f"PubChem compounds absent from it takes that to **{n_after} over "
        f"{scaffolds_after}**.",
        "",
        "## Headline numbers, and why they mislead",
        "",
        "| | Best model | MAE | R2 | Spearman |",
        "|---|---|---|---|---|",
        f"| Before | {best_before['model']} ({best_before['features']}) | "
        f"{best_before['mae_mean']:.3f} | {best_before['r2_mean']:+.3f} | "
        f"{best_before['spearman_mean']:.3f} |",
        f"| After | {best_after['model']} ({best_after['features']}) | "
        f"{best_after['mae_mean']:.3f} | {best_after['r2_mean']:+.3f} | "
        f"{best_after['spearman_mean']:.3f} |",
        "",
        "Read quickly, that says the expansion fixed the model: R2 crossed "
        "from negative",
        "to positive, which sounds like the difference between a model that "
        "is worse than",
        "guessing the mean and one that is not.",
        "",
        "It is not that. Scaffold-split folds on a set this size vary by "
        f"about +/-{result['fold_sd']:.2f} log",
        "units between themselves, so a difference of "
        f"{abs(best_after['mae_mean'] - best_before['mae_mean']):.3f} in the "
        "mean carries no weight.",
        f"Comparing the per-fold scores directly gives **p = "
        f"{result['p_value']:.2f}**"
        + (
            "**, which is not significant.**"
            if not significant
            else "**, which is significant.**"
        ),
        "",
        "An R2 of +0.03 is not a model that works. It is a model that is "
        "indistinguishable",
        "from predicting the training mean, described with a different sign.",
        "",
        "## Like-for-like, every configuration",
        "",
        "The best configuration can change between runs for reasons unrelated "
        "to the data,",
        "so each model is compared against itself.",
        "",
        "| Model | Features | MAE before | MAE after | Change |",
        "|---|---|---|---|---|",
    ]
    for row in table.itertuples(index=False):
        lines.append(
            f"| {row.model} | {row.features} | "
            f"{row.mae_before:.3f} +/- {row.sd_before:.3f} | "
            f"{row.mae_after:.3f} +/- {row.sd_after:.3f} | "
            f"{row.delta:+.3f} |"
        )

    lines += [
        "",
        f"**{result['improved']} of {result['total']}** configurations "
        "improved. If the direction were a",
        f"coin flip that would happen with probability "
        f"{result['sign_p']:.2f}.",
        "",
    ]

    if result["improved"] >= 0.75 * max(result["total"], 1):
        lines += [
            "Nearly every configuration moved the same way, which is more "
            "interesting than",
            "any single comparison: a change too small to reach significance "
            "on magnitude can",
            "still be real if independent models agree on its direction.",
            "",
            "**That sign-test p-value should not be read at face value.** It "
            "assumes the",
            "configurations are independent samples, and they are emphatically "
            "not: all of",
            "them see the same compounds, the same scaffold folds and largely "
            "overlapping",
            "feature blocks, with two of the three algorithms being tree "
            "ensembles. Positively",
            "correlated tests make a shared direction far more likely than "
            "chance would",
            "suggest, so the true evidence is weaker than "
            f"{result['sign_p']:.3f} implies -- how much",
            "weaker is not quantifiable from these runs.",
            "",
            "The defensible statement is the modest one: the direction is "
            "consistent and the",
            "magnitude is inside fold-to-fold noise, which is what adding 5% "
            "more data to a",
            "small set should be expected to look like.",
            "",
        ]

    lines += [
        "## What this means for the project",
        "",
        "Adding 5% more compounds did not measurably improve the model, and "
        "nobody should",
        "expect it to have. The useful conclusion is about scale: if nine "
        "compounds move",
        "the needle this little, the gap between this dataset and a usable "
        "one is not",
        "tens of compounds but hundreds.",
        "",
        "It also settles the 'expand beyond ChEMBL' recommendation that this "
        "project had",
        "been carrying as future work. The public record was checked, it "
        "yielded nine",
        "usable compounds, and they were not enough. That recommendation "
        "should not be",
        "repeated as though it were still untried.",
        "",
        "The honest reading of both datasets is unchanged: the model ranks "
        "compounds",
        "weakly and cannot predict absolute potency for unseen chemistry.",
        "",
    ]
    (DOCS / "DATA_EXPANSION.md").write_text("\n".join(lines))


def main() -> int:
    before = RESULTS / "models"
    after = RESULTS / "models_combined"
    for path in (before, after):
        if not (path / "metrics.csv").exists():
            print(f"{path / 'metrics.csv'} not found", file=sys.stderr)
            return 1

    chembl = pd.read_csv(PROCESSED / "lgmn_regression.csv")
    combined = pd.read_csv(PROCESSED / "lgmn_combined.csv")

    result = compare(before, after)

    print(
        f"Before: {len(chembl)} compounds, "
        f"{chembl['scaffold'].nunique()} scaffolds -> "
        f"MAE {result['best_before']['mae_mean']:.3f}, "
        f"R2 {result['best_before']['r2_mean']:+.3f}"
    )
    print(
        f"After:  {len(combined)} compounds, "
        f"{combined['scaffold'].nunique()} scaffolds -> "
        f"MAE {result['best_after']['mae_mean']:.3f}, "
        f"R2 {result['best_after']['r2_mean']:+.3f}"
    )
    print(
        f"\nper-fold comparison: p = {result['p_value']:.3f} "
        f"(fold-to-fold sd {result['fold_sd']:.2f})"
    )
    print(
        f"configurations improved: {result['improved']}/{result['total']} "
        f"(sign test p = {result['sign_p']:.3f})"
    )
    print(
        "\nVerdict: "
        + (
            "no measurable improvement; direction consistent but within noise"
            if result["p_value"] >= 0.05
            else "measurable improvement"
        )
    )

    write_doc(
        result,
        len(chembl),
        len(combined),
        chembl["scaffold"].nunique(),
        combined["scaffold"].nunique(),
    )
    print(f"\nWrote {DOCS / 'DATA_EXPANSION.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
