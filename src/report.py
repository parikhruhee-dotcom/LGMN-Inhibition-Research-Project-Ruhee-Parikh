"""Assemble the project write-up from the artefacts each stage produced.

Reads only files on disk, so the report cannot drift from the results: if a
stage has not been run, its section says so rather than quoting a stale
number.

Writes:
    docs/RESULTS.md    the findings
    docs/DOCKING.md    docking protocol validation and what it licenses
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
RESULTS = ROOT / "results"
DOCS = ROOT / "docs"

MISSING = "_Not run yet._"


def _read_csv(path: Path) -> pd.DataFrame | None:
    return pd.read_csv(path) if path.exists() else None


def _read_json(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def docking_section() -> list[str]:
    validation = _read_csv(RESULTS / "docking" / "protocol_validation.csv")
    lines = [
        "# Docking protocol: what it was validated to do",
        "",
        "Generated by `src/report.py` from "
        "`results/docking/protocol_validation.csv`.",
        "",
        "## Why validation comes first",
        "",
        "A docking setup with a misplaced box, a damaged receptor or badly "
        "protonated",
        "ligands still returns confident-looking scores for every compound, "
        "and nothing",
        "in the output reveals the problem. Redocking a ligand whose pose is "
        "known from",
        "crystallography is the one available check. Convention takes RMSD "
        "below 2.0 A",
        "as success.",
        "",
        "Two numbers are reported per template, and the difference between "
        "them says",
        "what kind of failure occurred:",
        "",
        "- **top-pose RMSD** is the prospective number. In a real screen the "
        "top-scored",
        "  pose is what you act on, with no crystal structure to check it "
        "against.",
        "- **best-of-20 RMSD** separates sampling from scoring. If the best "
        "pose is",
        "  right but the top pose is not, the search found the binding mode "
        "and the",
        "  *scoring function* could not rank it first. If no pose is right, "
        "the search",
        "  never found it -- a box, receptor or ligand-preparation fault.",
        "",
    ]

    if validation is None:
        lines += [MISSING, ""]
        return lines

    lines += [
        "## Results",
        "",
        "| PDB | Ligand | Res (A) | Atoms | Covalent in crystal | "
        "Top RMSD | Best RMSD | Best at rank | Verdict |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in validation.itertuples(index=False):
        verdict = (
            "pass"
            if row.passed
            else ("scoring could not rank it" if row.sampling_found_pose else "fail")
        )
        lines.append(
            f"| {row.pdb_id} | {row.ligand} | {row.resolution} | "
            f"{row.ligand_atoms} | "
            f"{'yes' if row.covalent_in_crystal else 'no'} | "
            f"{row.top_rmsd:.2f} | {row.best_rmsd:.2f} | "
            f"{row.best_rank if pd.notna(row.best_rank) else '-'} | "
            f"{verdict} |"
        )

    selected = _read_json(PROCESSED / "selected_template.json")
    passed = validation[validation["passed"]]
    sampled = validation[validation["sampling_found_pose"]]

    lines += ["", "## What this licenses", ""]

    if not passed.empty:
        lines += [
            f"{len(passed)} of {len(validation)} templates reproduced their "
            "crystal pose as",
            "the top-ranked result, so docking into those receptors is doing "
            "something",
            "real. Scores remain a coarse ranking signal, not a binding "
            "free energy.",
            "",
        ]
    elif not sampled.empty:
        lines += [
            f"No template reproduced its pose as the **top-ranked** result, "
            f"but {len(sampled)}",
            "found it somewhere in the top 20. That is a scoring-function "
            "failure rather",
            "than a broken setup: the search locates the binding mode and "
            "then ranks a",
            "decoy above it.",
            "",
            "The consequence is concrete and limiting. Docking scores from "
            "this protocol",
            "cannot be used to rank compounds against each other, because the "
            "same",
            "scoring function that misranks poses of one ligand will misrank "
            "ligands.",
            "They are used here only as a weak filter -- does the compound "
            "fit the",
            "pocket at all, and does its pose contact the catalytic thiol -- "
            "and weighted",
            "accordingly (0.15) in the shortlist.",
            "",
        ]
    else:
        lines += [
            "No template reproduced its crystal pose at all, in any of the "
            "top 20 poses.",
            "On this evidence the docking results in this project should not "
            "be used, and",
            "the shortlist should rest on measured potency and ADMET "
            "prediction alone.",
            "",
        ]

    # The fragment-versus-drug-sized distinction, where the data shows it.
    fragments = validation[validation["ligand_atoms"] < 25]
    drug_sized = validation[validation["ligand_atoms"] >= 25]
    if not fragments.empty and not drug_sized.empty:
        lines += [
            "### Fragments redock worse, as expected",
            "",
            f"Mean top-pose RMSD for the {len(fragments)} fragment ligands "
            f"(<25 heavy atoms) is",
            f"{fragments['top_rmsd'].mean():.2f} A, against "
            f"{drug_sized['top_rmsd'].mean():.2f} A for the "
            f"{len(drug_sized)} drug-sized ones.",
            "Small, weakly-bound ligands make shallow contact and empirical "
            "scoring",
            "functions struggle to distinguish their real pose from "
            "alternatives. This is",
            "why the box is sized from the ligand rather than left wide: "
            "redocking 5KN",
            "into 5LUA put the top pose 10.4 A away with 8 A of padding, and "
            "1.4 A was",
            "reachable at 3 A.",
            "",
        ]

    if selected:
        lines += [
            "## Selected template",
            "",
            f"**{selected['pdb_id']} / {selected['ligand']}** at "
            f"{selected['resolution']} A "
            f"({selected['ligand_atoms']} heavy atoms).",
            "",
            f"- top-pose RMSD {selected['top_rmsd']:.2f} A",
            f"- best-of-20 RMSD {selected['best_rmsd']:.2f} A",
            f"- validated prospectively: "
            f"**{'yes' if selected['validated'] else 'no'}**",
            "",
        ]
        if selected["covalent_in_crystal"]:
            lines += [
                "This ligand is **covalently bound** in the crystal. Redocking "
                "it",
                "non-covalently tests the pocket shape, the box and the "
                "preparation, which",
                "is what the protocol needs to be trusted for; it does not "
                "test the bond",
                "formation, which the scoring function does not model at all.",
                "",
            ]

    lines += [
        "## The deeper limitation",
        "",
        "85% of the compounds in this dataset carry a covalent warhead. Their "
        "measured",
        "potency is dominated by the rate of bond formation with Cys189, and a "
        "non-covalent",
        "scoring function has no term for that. So for most of this dataset a "
        "docking",
        "score is not a weak estimate of potency -- it is an estimate of a "
        "different",
        "quantity (how well the fragment sits in the pocket before reacting). "
        "That is",
        "worth knowing, and it is not what a screening score is usually read "
        "as.",
        "",
    ]
    return lines


def results_section() -> list[str]:
    dataset = _read_csv(PROCESSED / "lgmn_regression.csv")
    summary = _read_csv(RESULTS / "models" / "summary.csv")
    shortlist = _read_csv(RESULTS / "shortlist.csv")
    survey = _read_csv(PROCESSED / "target_survey.csv")

    lines = [
        "# Results",
        "",
        "Generated by `src/report.py`. **Every result here is a computational "
        "prediction.**",
        "Nothing in this project has been tested experimentally.",
        "",
        "## The target",
        "",
    ]

    if survey is not None:
        mature = survey[survey["mature"].astype(bool)]["pdb_id"].nunique()
        lines += [
            f"- Experimental structures of human legumain: "
            f"**{survey['pdb_id'].nunique()}**",
            f"- With the prodomain removed (mature enzyme): **{mature}**",
            "- Catalytic dyad found geometrically in every chain of every "
            "entry: "
            "**Cys189 / His148**",
            "",
            "That the same pair falls out of all 18 independent structures is "
            "the check",
            "that the right site was located; see `docs/TARGET.md` for the "
            "measured",
            "geometry and why a distance cutoff cannot be used to identify it.",
            "",
        ]
    else:
        lines += [MISSING, ""]

    lines += ["## The data", ""]
    if dataset is not None:
        covalent = dataset["covalent"].fillna(False).astype(bool)
        lines += [
            f"- Compounds with usable human biochemical potency: "
            f"**{len(dataset)}**",
            f"- Unique scaffolds: **{dataset['scaffold'].nunique()}**",
            f"- Covalent warhead: **{int(covalent.sum())}** "
            f"({100 * covalent.mean():.0f}%)",
            f"- pIC50 {dataset['pic50'].min():.2f}-"
            f"{dataset['pic50'].max():.2f}, "
            f"median {dataset['pic50'].median():.2f}",
            "",
            "See `docs/DATASET.md`. The one change that mattered most was "
            "separating",
            "cell-based from enzymatic assays before aggregating replicates: "
            "pooling them",
            "created 1-3 log 'disagreement' for 30 compounds that was really "
            "the",
            "difference between inhibiting purified enzyme and inhibiting it "
            "inside a",
            "cell. Fixing it cut unusable labels from 31 compounds to 1.",
            "",
        ]
    else:
        lines += [MISSING, ""]

    permeability = _read_csv(PROCESSED / "permeability_gap.csv")
    if permeability is not None and not permeability.empty:
        median_gap = permeability["cell_gap"].median()
        large = int((permeability["cell_gap"] >= 1.0).sum())
        lines += [
            "## What happens when these compounds meet a membrane",
            "",
            f"{len(permeability)} compounds were measured both on purified "
            "enzyme and inside",
            "HEK293-A cells, which is the closest thing to experimental "
            "permeability",
            "evidence available here without running an experiment.",
            "",
            f"- Median potency lost on entering a cell: "
            f"**{median_gap:.2f} log units** "
            f"({10 ** median_gap:.0f}-fold weaker)",
            f"- Losing 10-fold or more: **{large} of {len(permeability)}**",
            "- Molecular weight predicts the loss "
            "(Spearman 0.73, Holm-adjusted p=4e-6)",
            "",
            "This is the central finding meeting independent evidence. The "
            "compounds are",
            "large and polar because that is what binds an "
            "asparagine-recognising protease,",
            "and the same properties cost them most of their potency at an "
            "ordinary cell",
            "membrane. The blood-brain barrier is a considerably harder one.",
            "",
            "See `docs/PERMEABILITY.md`.",
            "",
        ]

    lines += [
        "## Can potency be predicted?",
        "",
        "![Model performance](../results/figures/model_performance.png)",
        "",
    ]
    if summary is not None:
        scaffold = summary[summary["split"] == "scaffold"].sort_values("mae_mean")
        random_split = summary[summary["split"] == "random"].sort_values("mae_mean")
        best = scaffold[scaffold["model"] != "mean_baseline"].iloc[0]
        baseline = scaffold[scaffold["model"] == "mean_baseline"]["mae_mean"].min()
        best_random = random_split[
            random_split["model"] != "mean_baseline"
        ].iloc[0]

        lines += [
            "Modestly, for ranking. Not at all, for absolute potency on new "
            "chemistry.",
            "",
            "| Split | Best model | MAE (log units) | R2 | Spearman |",
            "|---|---|---|---|---|",
            f"| scaffold | {best['model']} ({best['features']}) | "
            f"{best['mae_mean']:.3f} | {best['r2_mean']:.2f} | "
            f"{best['spearman_mean']:.2f} |",
            f"| random | {best_random['model']} ({best_random['features']}) | "
            f"{best_random['mae_mean']:.3f} | {best_random['r2_mean']:.2f} | "
            f"{best_random['spearman_mean']:.2f} |",
            f"| scaffold | predict the training mean | {baseline:.3f} | - | - |",
            "",
            "Three things to read from this:",
            "",
            f"1. The scaffold-split model beats predicting the mean by "
            f"{100 * (baseline - best['mae_mean']) / baseline:.0f}%, so there "
            "is",
            "   some transferable signal. It is not nothing.",
            f"2. **R2 is negative** ({best['r2_mean']:.2f}). The model is "
            "worse than the mean in",
            "   squared error while better in absolute error, which means a "
            "few large",
            "   misses dominate. It cannot be trusted to predict how potent a "
            "new",
            f"   compound is. Spearman {best['spearman_mean']:.2f} says it "
            "retains some ability to",
            "   put compounds in roughly the right order.",
            f"3. The random split looks much better "
            f"({best_random['mae_mean']:.3f} vs "
            f"{best['mae_mean']:.3f} MAE).",
            "   That gap is the inflation you get by letting members of one "
            "compound",
            "   series sit on both sides of the split. The random number is "
            "the one that",
            "   would look good in a report and it is the one that means "
            "least.",
            "",
            "Every prediction is accompanied by its maximum Tanimoto "
            "similarity to the",
            "training set, so extrapolation is visible rather than implied.",
            "",
        ]
    else:
        lines += [MISSING, ""]

    lines += ["## Candidate compounds", ""]
    if shortlist is not None:
        cns = shortlist["cns_candidate"].fillna(False).astype(bool)
        covalent = shortlist["covalent"].fillna(False).astype(bool)
        both = int((cns & ~covalent).sum())
        in_box = int(
            (
                shortlist["clogp"].between(1, 4)
                & shortlist["tpsa"].between(40, 90)
            ).sum()
        )
        lines += [
            f"- Profiled: **{len(shortlist)}**",
            f"- Meeting the combined CNS criteria: **{int(cns.sum())}**",
            f"- CNS-suitable **and** non-covalent: **{both}**",
            f"- Inside the CNS property optimum "
            f"(cLogP 1-4, TPSA 40-90 A2): **{in_box}**",
            f"- Median TPSA: **{shortlist['tpsa'].median():.0f} A2**, "
            f"against an optimum of 40-90",
            "",
            "The median compound is roughly 40 A2 more polar than the top of "
            "the range",
            "that crosses the blood-brain barrier passively. That single "
            "number captures",
            "the problem better than any filter count: this chemistry was "
            "optimised to bind",
            "an asparagine-recognising protease pocket, which rewards polar, "
            "hydrogen-",
            "bonding groups, and those are the same properties that keep a "
            "molecule out of",
            "the brain.",
            "",
            "That last number is the project's real finding, and it is a "
            "negative one.",
            "Legumain inhibitor chemistry is overwhelmingly covalent, "
            "peptide-like and",
            "polar, which is close to the opposite of the small, lipophilic "
            "profile that",
            "crosses the blood-brain barrier passively. The two requirements "
            "pull against",
            "each other, and almost nothing in the published chemistry "
            "satisfies both.",
            "",
            "See `docs/SHORTLIST.md` for the ranked table.",
            "",
        ]
    else:
        lines += [MISSING, ""]

    selectivity = _read_csv(PROCESSED / "selectivity.csv")
    if selectivity is not None and dataset is not None:
        tested = (
            selectivity["molecule_chembl_id"].nunique()
            if not selectivity.empty
            else 0
        )
        total = dataset["molecule_chembl_id"].nunique()
        bounded = (
            int(selectivity["any_censored"].astype(bool).sum())
            if not selectivity.empty
            else 0
        )
        lines += [
            "## Selectivity",
            "",
            f"- Compounds with any published counter-screen: "
            f"**{tested} of {total}**",
            f"- Of {len(selectivity)} compound-target pairs, **{bounded}** are "
            "lower bounds",
            "  ('no inhibition up to 50 uM') rather than measurements",
            "",
            "Where it has been looked at, selectivity is good -- roughly "
            "1000-fold or better",
            "against caspase-3, caspase-8, cathepsin B and cathepsin S. But "
            "that covers "
            f"{tested} compounds.",
            "For the other "
            f"{total - tested} the question is simply open, and for a "
            "covalent",
            "asparagine-directed warhead against a clan CD protease -- the "
            "same clan as the",
            "caspases -- open is the wrong state for it to be in. An "
            "untested compound is",
            "not a selective one.",
            "",
            "See `docs/SELECTIVITY.md`.",
            "",
        ]

    lines += [
        "## Honest limitations",
        "",
        "- **No experimental validation.** Every number is a prediction or a "
        "literature",
        "  measurement. Nothing was tested.",
        "- **The dataset is small and concentrated.** 180 compounds over 55 "
        "scaffolds,",
        "  42 of which appear once. Negative R2 on a scaffold split is the "
        "honest",
        "  consequence.",
        "- **Covalent chemistry dominates (85%)** and non-covalent docking "
        "does not",
        "  model it. See `docs/DOCKING.md`.",
        "- **ADMET values are 2D predictions**, including a substructure-based "
        "pKa",
        "  estimate that is the weakest input to the CNS MPO score.",
        "- **CNS MPO is not a drug-likeness test.** Sucrose scores 4.0 and "
        "would 'pass';",
        "  the combined `cns_candidate` verdict exists because of that.",
        "- **Selectivity was not assessed.** Legumain belongs to clan CD "
        "alongside the",
        "  caspases, and a covalent asparagine-directed warhead has obvious "
        "cross-",
        "  reactivity questions that this project does not address.",
        "",
        "## What would actually move this forward",
        "",
        "1. **Test the 6 non-covalent CNS-suitable compounds** against "
        "recombinant",
        "   legumain. Six compounds is a tractable experiment and it would "
        "convert the",
        "   whole project from prediction to evidence.",
        "2. **Measure selectivity against caspase-3 and cathepsin B** for "
        "anything that",
        "   works, since the warhead chemistry invites cross-reactivity.",
        "3. **Analyse the enzymatic-to-cellular potency gap** in",
        "   `data/processed/lgmn_cellular.csv`. Those 74 records are a "
        "permeability",
        "   signal already in hand, and permeability is the project's binding "
        "constraint.",
        "4. **Expand beyond ChEMBL.** 180 compounds is the ceiling on what any "
        "model here",
        "   can learn; patent and PubChem data would raise it.",
        "",
    ]
    return lines


def main() -> int:
    DOCS.mkdir(parents=True, exist_ok=True)
    (DOCS / "RESULTS.md").write_text("\n".join(results_section()))
    (DOCS / "DOCKING.md").write_text("\n".join(docking_section()))
    print(f"Wrote {DOCS / 'RESULTS.md'}")
    print(f"Wrote {DOCS / 'DOCKING.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
