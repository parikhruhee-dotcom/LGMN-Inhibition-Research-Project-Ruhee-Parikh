"""Assemble the project write-up from the artefacts each stage produced.

Reads only files on disk, so the report cannot drift from the results: if a
stage has not been run, its section says so rather than quoting a stale
number.

Writes:
    docs/RESULTS.md    the findings
    docs/DOCKING.md    docking protocol validation and what it licenses
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
RESULTS = ROOT / "results"
DOCS = ROOT / "docs"

MISSING = "_Not run yet._"

# Descriptor column names are terse by design; prose should not be.
PROPERTY_LABELS = {
    "mw": "Molecular weight",
    "clogp": "cLogP",
    "tpsa": "TPSA",
    "hbd": "Hydrogen-bond donors",
    "hba": "Hydrogen-bond acceptors",
    "rotb": "Rotatable bonds",
    "fsp3": "Fraction sp3 carbon",
}


def _read_csv(path: Path) -> pd.DataFrame | None:
    return pd.read_csv(path) if path.exists() else None


def _read_json(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def docking_section() -> list[str]:
    validation = _read_csv(RESULTS / "docking" / "protocol_validation.csv")
    lines = [
        "# Docking protocol: what it was validated to do",
        "",
        "Generated by `src/report.py` from "
        "`results/docking/protocol_validation.csv`.",
        "",
        "## Why validation comes first",
        "",
        "A docking setup with a misplaced box, a damaged receptor or badly "
        "protonated",
        "ligands still returns confident-looking scores for every compound, "
        "and nothing",
        "in the output reveals the problem. Redocking a ligand whose pose is "
        "known from",
        "crystallography is the one available check. Convention takes RMSD "
        "below 2.0 A",
        "as success.",
        "",
        "Two numbers are reported per template, and the difference between "
        "them says",
        "what kind of failure occurred:",
        "",
        "- **top-pose RMSD** is the prospective number. In a real screen the "
        "top-scored",
        "  pose is what you act on, with no crystal structure to check it "
        "against.",
        "- **best-of-20 RMSD** separates sampling from scoring. If the best "
        "pose is",
        "  right but the top pose is not, the search found the binding mode "
        "and the",
        "  *scoring function* could not rank it first. If no pose is right, "
        "the search",
        "  never found it -- a box, receptor or ligand-preparation fault.",
        "",
    ]

    if validation is None:
        lines += [MISSING, ""]
        return lines

    lines += [
        "## Results",
        "",
        "| PDB | Ligand | Res (A) | Atoms | Covalent in crystal | "
        "Top RMSD | Best RMSD | Best at rank | Verdict |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in validation.itertuples(index=False):
        verdict = (
            "pass"
            if row.passed
            else ("scoring could not rank it" if row.sampling_found_pose else "fail")
        )
        lines.append(
            f"| {row.pdb_id} | {row.ligand} | {row.resolution} | "
            f"{row.ligand_atoms} | "
            f"{'yes' if row.covalent_in_crystal else 'no'} | "
            f"{row.top_rmsd:.2f} | {row.best_rmsd:.2f} | "
            f"{row.best_rank if pd.notna(row.best_rank) else '-'} | "
            f"{verdict} |"
        )

    selected = _read_json(PROCESSED / "selected_template.json")
    passed = validation[validation["passed"]]
    sampled = validation[validation["sampling_found_pose"]]

    lines += ["", "## What this licenses", ""]

    if not passed.empty:
        lines += [
            f"{len(passed)} of {len(validation)} templates reproduced their "
            "crystal pose as",
            "the top-ranked result, so docking into those receptors is doing "
            "something",
            "real. Scores remain a coarse ranking signal, not a binding "
            "free energy.",
            "",
        ]
    elif not sampled.empty:
        lines += [
            f"No template reproduced its pose as the **top-ranked** result, "
            f"but {len(sampled)}",
            "found it somewhere in the top 20. That is a scoring-function "
            "failure rather",
            "than a broken setup: the search locates the binding mode and "
            "then ranks a",
            "decoy above it.",
            "",
            "The consequence is concrete and limiting. Docking scores from "
            "this protocol",
            "cannot be used to rank compounds against each other, because the "
            "same",
            "scoring function that misranks poses of one ligand will misrank "
            "ligands.",
            "They are used here only as a weak filter -- does the compound "
            "fit the",
            "pocket at all, and does its pose contact the catalytic thiol -- "
            "and weighted",
            "accordingly (0.15) in the shortlist.",
            "",
        ]
    else:
        lines += [
            "No template reproduced its crystal pose at all, in any of the "
            "top 20 poses.",
            "On this evidence the docking results in this project should not "
            "be used, and",
            "the shortlist should rest on measured potency and ADMET "
            "prediction alone.",
            "",
        ]

    # The fragment-versus-drug-sized distinction, where the data shows it.
    fragments = validation[validation["ligand_atoms"] < 25]
    drug_sized = validation[validation["ligand_atoms"] >= 25]
    if not fragments.empty and not drug_sized.empty:
        lines += [
            "### Fragments redock worse, as expected",
            "",
            f"Mean top-pose RMSD for the {len(fragments)} fragment ligands "
            f"(<25 heavy atoms) is",
            f"{fragments['top_rmsd'].mean():.2f} A, against "
            f"{drug_sized['top_rmsd'].mean():.2f} A for the "
            f"{len(drug_sized)} drug-sized ones.",
            "Small, weakly-bound ligands make shallow contact and empirical "
            "scoring",
            "functions struggle to distinguish their real pose from "
            "alternatives. This is",
            "why the box is sized from the ligand rather than left wide: "
            "redocking 5KN",
            "into 5LUA put the top pose 10.4 A away with 8 A of padding, and "
            "1.4 A was",
            "reachable at 3 A.",
            "",
        ]

    if selected:
        lines += [
            "## Selected template",
            "",
            f"**{selected['pdb_id']} / {selected['ligand']}** at "
            f"{selected['resolution']} A "
            f"({selected['ligand_atoms']} heavy atoms).",
            "",
            f"- top-pose RMSD {selected['top_rmsd']:.2f} A",
            f"- best-of-20 RMSD {selected['best_rmsd']:.2f} A",
            f"- validated prospectively: "
            f"**{'yes' if selected['validated'] else 'no'}**",
            "",
        ]
        if selected["covalent_in_crystal"]:
            lines += [
                "This ligand is **covalently bound** in the crystal. Redocking "
                "it",
                "non-covalently tests the pocket shape, the box and the "
                "preparation, which",
                "is what the protocol needs to be trusted for; it does not "
                "test the bond",
                "formation, which the scoring function does not model at all.",
                "",
            ]

    analysis = _read_json(RESULTS / "docking" / "screen_analysis.json")
    if analysis:
        lines += [
            "## Does the score actually track potency?",
            "",
            "The redocking result above predicts that it should not: a "
            "function that cannot",
            "rank poses of one ligand has little reason to rank ligands. But "
            "every compound",
            "here has a published pIC50, so the question can be measured "
            "instead of argued.",
            "",
            "![Docking score vs potency]"
            "(../results/figures/docking_vs_potency.png)",
            "",
        ]

        if not analysis.get("complete"):
            lines += [
                "> **This is a partial run.** The numbers below will move as "
                "the screen",
                "> finishes.",
                "",
            ]

        rep = analysis.get("representativeness") or {}
        if rep and not rep.get("representative", True):
            lines += [
                f"> **The scored subset is not representative.** Its median "
                f"pIC50 is "
                f"{rep['subset_median_pic50']:.2f} against "
                f"{rep['dataset_median_pic50']:.2f} for the full dataset. A "
                "correlation",
                "> measured over a restricted potency range is not comparable "
                "to one over the",
                "> full range, so treat what follows as provisional.",
                "",
            ]

        lines += [
            f"Scored compounds: **{analysis['n_scored']}**, affinity "
            f"{analysis['affinity_min']:.2f} to "
            f"{analysis['affinity_max']:.2f} kcal/mol.",
            "",
            "A working scoring function gives a **negative** correlation: a "
            "more negative",
            "affinity should mean a more potent compound.",
            "",
            "| Subset | n | Spearman | p | Direction |",
            "|---|---|---|---|---|",
        ]
        for entry in analysis.get("correlations", []):
            if "spearman_rho" not in entry:
                lines.append(
                    f"| {entry['subset']} | {entry['n']} | - | - | "
                    f"{entry.get('note', 'not evaluated')} |"
                )
                continue
            lines.append(
                f"| {entry['subset']} | {entry['n']} | "
                f"{entry['spearman_rho']:+.3f} | "
                f"{entry['spearman_p']:.3g} | "
                f"{'correct' if entry['direction_correct'] else 'WRONG'} |"
            )

        size = analysis.get("size_controlled") or {}
        if size:
            lines += [
                "",
                "### Is it just molecular size?",
                "",
                "Vina-family scores grow more negative with ligand size, and "
                "in this dataset",
                f"potency also rises with size "
                f"(rho {size['size_vs_potency_rho']:+.2f}). A score that "
                "merely tracked size would",
                "therefore produce a convincing correlation with potency "
                "while knowing nothing",
                "about binding.",
                "",
                f"- affinity vs heavy atoms: "
                f"**{size['affinity_vs_size_rho']:+.2f}**",
                f"- size vs potency: **{size['size_vs_potency_rho']:+.2f}**",
                f"- affinity vs potency, controlling for size: "
                f"**{size['partial_rho']:+.3f}** "
                f"(p={size['partial_p']:.3g})",
                "",
            ]
            if size.get("survives_size_control"):
                lines += [
                    "The relationship survives the control, so it is not "
                    "simply a molecular",
                    "weight effect. That is a more positive result than the "
                    "redocking validation",
                    "predicted, and worth stating plainly in both directions: "
                    "the scoring",
                    "function cannot place a ligand correctly in the pocket, "
                    "yet retains some",
                    "ability to tell potent compounds from weak ones across a "
                    "series.",
                    "",
                ]
            else:
                lines += [
                    "The relationship does **not** survive the control. The "
                    "apparent agreement",
                    "between docking score and potency is an artefact of "
                    "molecular size, and the",
                    "scores carry no usable information about binding on this "
                    "target.",
                    "",
                ]

        subsets = analysis.get("size_controlled_subsets") or {}
        non_cov = subsets.get("non_covalent") or {}
        cov = subsets.get("covalent") or {}
        if non_cov and cov:
            lines += [
                "### Split by mechanism, the picture changes",
                "",
                "The whole-set number averages two populations with different "
                "physics. A",
                "scoring function has no term for covalent bond formation, so "
                "for the 85% of",
                "these compounds that inhibit covalently, potency is governed "
                "by a reaction rate",
                "the score cannot see. Controlling for ligand size within "
                "each group:",
                "",
                "| Subset | n | Partial Spearman | p | Survives size control |",
                "|---|---|---|---|---|",
                f"| Non-covalent | {non_cov['n']} | "
                f"{non_cov['partial_rho']:+.3f} | "
                f"{non_cov['partial_p']:.3g} | "
                f"{'yes' if non_cov['survives_size_control'] else 'no'} |",
                f"| Covalent | {cov['n']} | {cov['partial_rho']:+.3f} | "
                f"{cov['partial_p']:.3g} | "
                f"{'yes' if cov['survives_size_control'] else 'no'} |",
                "",
            ]
            if non_cov["survives_size_control"] and not cov[
                "survives_size_control"
            ]:
                lines += [
                    "That is the result worth taking from this screen, and it "
                    "is more useful",
                    "than the headline correlation. Docking carries real "
                    "signal exactly where its",
                    "physics applies -- non-covalent binding -- and none "
                    "where it does not. The",
                    "whole-set figure looks null only because the covalent "
                    "majority swamps a real",
                    "relationship in the minority.",
                    "",
                    "It also matters for this project specifically. Every "
                    "compound on the",
                    "shortlist that is both non-covalent and CNS-suitable "
                    "falls in the subset where",
                    "docking scores mean something, so the scores can be "
                    "used to rank those",
                    "candidates against each other -- which is not true of "
                    "the dataset as a whole.",
                    "",
                ]

        enrich = analysis.get("enrichment") or {}
        if enrich.get("enrichment_factor") is not None:
            lines += [
                "### What a top slice would actually give you",
                "",
                "Virtual screening is used to pick a top slice, not to "
                "predict potencies, so",
                "enrichment matters as much as correlation. 'Active' here "
                "means the top",
                "quartile of measured potency "
                f"(pIC50 >= {enrich['active_threshold_pic50']:.2f}); a fixed "
                "100 nM cut is",
                "meaningless on a set of published inhibitors where most "
                "compounds clear it.",
                "",
                f"- Top {int(100 * enrich['top_fraction'])}% by docking score: "
                f"**{100 * enrich['top_active_rate']:.0f}%** are top-quartile "
                "potent",
                f"- Whole set: "
                f"**{100 * enrich['overall_active_rate']:.0f}%**",
                f"- Enrichment factor: "
                f"**{enrich['enrichment_factor']:.2f}x** "
                "(1.0 would be no better than random)",
                "",
            ]

    lines += [
        "## The deeper limitation",
        "",
        "85% of the compounds in this dataset carry a covalent warhead. Their "
        "measured",
        "potency is dominated by the rate of bond formation with Cys189, and a "
        "non-covalent",
        "scoring function has no term for that. So for most of this dataset a "
        "docking",
        "score is not a weak estimate of potency -- it is an estimate of a "
        "different",
        "quantity (how well the fragment sits in the pocket before reacting). "
        "That is",
        "worth knowing, and it is not what a screening score is usually read "
        "as.",
        "",
    ]
    return lines


def _model_verdict() -> str:
    """Summarise model performance from the measured scores."""
    summary = _read_csv(RESULTS / "models" / "summary.csv")
    if summary is None:
        return "not evaluated"
    scaffold = summary[summary["split"].eq("scaffold")]
    learned = scaffold[scaffold["model"].ne("mean_baseline")]
    if learned.empty:
        return "not evaluated"
    best = learned.sort_values("mae_mean").iloc[0]
    quality = "no" if best["r2_mean"] < 0.3 else "partly"
    return (
        f"Ranked weakly (Spearman {best['spearman_mean']:.2f}); "
        f"absolute potency {quality} (R2 {best['r2_mean']:+.2f})"
    )


def _permeability_verdict() -> str:
    stats = _read_json(PROCESSED / "permeability_stats.json")
    if not stats:
        return "not evaluated"
    label = PROPERTY_LABELS.get(
        stats.get("best_property"), stats.get("best_property")
    )
    tail = f"; {label.lower()} predicts it" if label else ""
    return f"Median {stats['fold_loss']:.0f}-fold potency loss{tail}"


def _selectivity_verdict() -> str:
    selectivity = _read_csv(PROCESSED / "selectivity.csv")
    dataset = _read_csv(PROCESSED / "lgmn_regression.csv")
    if selectivity is None or dataset is None:
        return "not evaluated"
    tested = (
        selectivity["molecule_chembl_id"].nunique()
        if not selectivity.empty
        else 0
    )
    total = dataset["molecule_chembl_id"].nunique()
    return f"Unknown for {total - tested} of {total}"


def results_section() -> list[str]:
    dataset = _read_csv(PROCESSED / "lgmn_regression.csv")
    summary = _read_csv(RESULTS / "models" / "summary.csv")
