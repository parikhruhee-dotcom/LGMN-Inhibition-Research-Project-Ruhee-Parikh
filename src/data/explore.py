"""Exploratory figures for the LGMN dataset.

The point of these is to show what the data can and cannot support before any
model is fitted. Three things decide that here: how little data there is, how
concentrated it is in a few scaffolds, and how dominated it is by covalent
chemistry.

Writes:
    results/figures/dataset_overview.png
    docs/DATASET.md
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
PROCESSED = ROOT / "data" / "processed"
FIGURE_DIR = ROOT / "results" / "figures"
DOCS = ROOT / "docs"


def make_figure(df: pd.DataFrame) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    FIGURE_DIR.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(2, 2, figsize=(13, 9))

    # --- potency distribution, split by mechanism ---
    covalent = df["covalent"].fillna(False).astype(bool)
    bins = np.linspace(df["pic50"].min(), df["pic50"].max(), 22)
    axes[0, 0].hist(
        [df.loc[covalent, "pic50"], df.loc[~covalent, "pic50"]],
        bins=bins,
        stacked=True,
        color=["#e76f51", "#2a9d8f"],
        label=[
            f"covalent warhead (n={int(covalent.sum())})",
            f"non-covalent (n={int((~covalent).sum())})",
        ],
    )
    axes[0, 0].set_xlabel("pIC50")
    axes[0, 0].set_ylabel("Compounds")
    axes[0, 0].set_title("Potency distribution by mechanism")
    axes[0, 0].legend(frameon=False, fontsize=8)

    # --- scaffold concentration ---
    counts = df["scaffold"].replace("", np.nan).value_counts()
    cumulative = counts.cumsum() / counts.sum() * 100
    axes[0, 1].plot(
        range(1, len(cumulative) + 1), cumulative.to_numpy(),
        marker="o", ms=3, color="#457b9d",
    )
    axes[0, 1].axhline(50, ls="--", lw=1, color="#555")
    half = int(np.searchsorted(cumulative.to_numpy(), 50) + 1)
    axes[0, 1].annotate(
        f"{half} scaffolds cover 50%",
        xy=(half, 50),
        xytext=(half + 3, 38),
        fontsize=8,
        arrowprops={"arrowstyle": "->", "color": "#555", "lw": 0.8},
    )
    axes[0, 1].set_xlabel("Scaffolds, most populated first")
    axes[0, 1].set_ylabel("Cumulative share of compounds (%)")
    axes[0, 1].set_title("How concentrated the chemistry is")

    # --- potency vs size, the ligand-efficiency view ---
    axes[1, 0].scatter(
        df["heavy_atoms"], df["pic50"],
        c=np.where(covalent, "#e76f51", "#2a9d8f"),
        s=34, alpha=0.75, edgecolor="none",
    )
    axes[1, 0].set_xlabel("Heavy atoms")
    axes[1, 0].set_ylabel("pIC50")
    axes[1, 0].set_title("Potency vs molecular size")

    # --- warhead classes ---
    warheads = (
        df.loc[covalent, "warheads"]
        .fillna("")
        .str.split("|")
        .explode()
        .replace("", np.nan)
        .dropna()
        .value_counts()
    )
    if not warheads.empty:
        axes[1, 1].barh(
            range(len(warheads)), warheads.to_numpy(), color="#e76f51"
        )
        axes[1, 1].set_yticks(range(len(warheads)))
        axes[1, 1].set_yticklabels(warheads.index, fontsize=8)
        axes[1, 1].invert_yaxis()
        axes[1, 1].set_xlabel("Compounds")
        axes[1, 1].set_title("Covalent warhead classes")
        for index, value in enumerate(warheads.to_numpy()):
            axes[1, 1].text(value, index, f" {value}", va="center", fontsize=8)

    for axis in axes.flat:
        axis.spines[["top", "right"]].set_visible(False)

    fig.tight_layout()
    fig.savefig(FIGURE_DIR / "dataset_overview.png", dpi=160)
    plt.close(fig)


def write_doc(df: pd.DataFrame) -> None:
    DOCS.mkdir(parents=True, exist_ok=True)

    covalent = df["covalent"].fillna(False).astype(bool)
    counts = df["scaffold"].replace("", np.nan).value_counts()
    cumulative = counts.cumsum() / counts.sum() * 100
    half = int(np.searchsorted(cumulative.to_numpy(), 50) + 1)
    singletons = int((counts == 1).sum())

    rejected_path = PROCESSED / "lgmn_rejected.csv"
    rejected = pd.read_csv(rejected_path) if rejected_path.exists() else pd.DataFrame()

    lines = [
        "# The LGMN dataset, and what it can support",
        "",
        "Generated by `src/data/explore.py`.",
        "",
        "## Size",
        "",
        f"- Compounds with a usable human biochemical potency: **{len(df)}**",
        f"- Unique Bemis-Murcko scaffolds: **{df['scaffold'].nunique()}**",
        f"- Scaffolds represented by a single compound: **{singletons}**",
        f"- Scaffolds covering half the dataset: **{half}**",
        f"- pIC50 range: **{df['pic50'].min():.2f} to {df['pic50'].max():.2f}** "
        f"(median {df['pic50'].median():.2f}, sd {df['pic50'].std():.2f})",
        "",
        "This is a small dataset by any QSAR standard, and it is not 180",
        "independent observations: the chemistry is concentrated, so a model "
        "that",
        "looks accurate under a random split is mostly recognising compound "
        "series",
        "it has already seen. That is why every reported metric in",
        "`docs/RESULTS.md` comes from a scaffold-grouped split.",
        "",
        "## Mechanism",
        "",
        f"- Carrying a covalent warhead: **{int(covalent.sum())}** "
        f"({100 * covalent.mean():.0f}%)",
        f"- Non-covalent: **{int((~covalent).sum())}**",
        "",
        "Legumain is a cysteine protease, so this is expected rather than a "
        "sampling",
        "artefact, but it constrains the whole project. Non-covalent docking "
        "scores",
        "are not meaningful for 85% of the compounds, and covalent chemistry "
        "carries",
        "selectivity and toxicity questions that a potency number does not "
        "capture.",
        "",
        "### Warhead classes",
        "",
    ]

    warheads = (
        df.loc[covalent, "warheads"].fillna("").str.split("|").explode()
        .replace("", np.nan).dropna().value_counts()
    )
    lines += ["| Warhead | Compounds |", "|---|---|"]
    for name, count in warheads.items():
        lines.append(f"| {name} | {count} |")

    lines += [
        "",
        "The nitrile count dominates because the largest published series "
        "against this",
        "target are electrophilic nitriles, which form a reversible "
        "thioimidate with",
        "the catalytic cysteine -- the adduct resolved in 7FQI.",
        "",
        "## What was discarded, and why",
        "",
    ]
    if not rejected.empty:
        lines += ["| Reason | Records |", "|---|---|"]
        for reason, count in rejected["reject_reason"].value_counts().items():
            lines.append(f"| `{reason}` | {count} |")
        lines += [
            "",
            "`endpoint_not_a_concentration` is mostly single-dose percent "
            "inhibition,",
            "which cannot be converted to a comparable potency. "
            "`assay_organism_not_human`",
            "is four Schistosoma mansoni measurements annotated against the "
            "human target",
            "in ChEMBL.",
            "",
        ]

    cellular_path = PROCESSED / "lgmn_cellular.csv"
    if cellular_path.exists():
        cellular = pd.read_csv(cellular_path)
        lines += [
            "## Cell-based records, kept separate",
            "",
            f"**{len(cellular)}** human cell-based measurements are held in",
            "`data/processed/lgmn_cellular.csv` rather than pooled with the "
            "enzymatic",
            "data. Pooling them was the single largest data-quality problem "
            "found in",
            "this project: it created 1-3 log unit 'replicate disagreement' "
            "for 30",
            "compounds that was really the difference between inhibiting "
            "purified enzyme",
            "and inhibiting it inside a cell. Separating them cut the number "
            "of compounds",
            "with unusable labels from 31 to 1.",
            "",
            "Those records are a permeability signal, not noise, and the gap "
            "between a",
            "compound's enzymatic and cellular IC50 is worth analysing on its "
            "own.",
            "",
        ]

    (DOCS / "DATASET.md").write_text("\n".join(lines))


def main() -> int:
    path = PROCESSED / "lgmn_regression.csv"
    if not path.exists():
        print(f"{path} not found; run src/data/prepare_dataset.py", file=sys.stderr)
        return 1

    df = pd.read_csv(path)
    make_figure(df)
    write_doc(df)
    print(f"Wrote {FIGURE_DIR / 'dataset_overview.png'}")
    print(f"Wrote {DOCS / 'DATASET.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
